"""Builds src/lib/voTiming.ts from VOICEOVER.md.

Each narration paragraph (ended by a "· · ·" pause) gets an estimated duration of
words / 2.6 + 2 s. When the real recordings exist, run with --measure to split
public/vo/story.m4a and public/vo/demo.m4a on their 2-second pauses (ffmpeg silencedetect)
and write the measured durations instead. Usage:

    python scripts/vo-table.py            # estimates
    python scripts/vo-table.py --measure  # real durations from the recordings, where present
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
md = open(os.path.join(ROOT, 'VOICEOVER.md'), encoding='utf8').read()
WPS = 2.6
PAUSE = 2.0


def parse(section):
    out = []
    for m in re.finditer(r'\*\*\[(.+?)\]\*\*\n(.*?)(?=\n\*\*\[|\n\*\(|\Z)', section, re.S):
        title, body = m.group(1), m.group(2)
        paras = [p.strip() for p in body.split('· · ·') if p.strip()]
        out.append({'title': title, 'paras': [{'words': len(p.split()), 'text': p} for p in paras]})
    return out


story_md = md.split('## Recording 1')[1].split('## Recording 2')[0]
demo_md = md.split('## Recording 2')[1]
story = parse(story_md)
demo = parse(demo_md)


def measure(path, n):
    """Durations of the n pause-separated segments of a recording (each segment includes its pause)."""
    if not os.path.exists(path):
        return None
    r = subprocess.run(['ffmpeg', '-hide_banner', '-i', path, '-af', 'silencedetect=noise=-35dB:d=1.4', '-f', 'null', '-'], capture_output=True, text=True)
    ends = [float(x) for x in re.findall(r'silence_end: ([0-9.]+)', r.stderr)]
    total = float(re.findall(r'Duration: (\d+):(\d+):([0-9.]+)', r.stderr) and (lambda h, m, s: int(h) * 3600 + int(m) * 60 + float(s))(*re.findall(r'Duration: (\d+):(\d+):([0-9.]+)', r.stderr)[0]))
    cuts = ends[: n - 1]
    if len(cuts) != n - 1:
        print(f'warning: {path}: found {len(ends)} pauses, expected {n - 1}; keeping estimates')
        return None
    bounds = [0.0] + cuts + [total]
    return [round(bounds[i + 1] - bounds[i], 2) for i in range(n)]


do_measure = '--measure' in sys.argv


def table(beats, audio):
    flat = [p for b in beats for p in b['paras']]
    meas = measure(os.path.join(ROOT, 'public', 'vo', audio), len(flat)) if do_measure else None
    k = 0
    rows = []
    for b in beats:
        secs = []
        for p in b['paras']:
            est = round(p['words'] / WPS + PAUSE, 2)
            secs.append(meas[k] if meas else est)
            k += 1
        rows.append({'title': b['title'], 'words': sum(p['words'] for p in b['paras']), 'paras': secs, 'seconds': round(sum(secs), 2), 'measured': bool(meas)})
    return rows


story_rows = table(story, 'story.m4a')
demo_rows = table(demo, 'demo.m4a')

ts = '''// GENERATED by scripts/vo-table.py from VOICEOVER.md — the single source of scene timing.
// Estimates use words / 2.6 + 2 s per paragraph. Run `python scripts/vo-table.py --measure` after the
// recordings land in public/vo/ to replace them with the real durations (split on the 2 s pauses).
export type VoRow = {title: string; words: number; paras: number[]; seconds: number; measured: boolean};
export const FPS = 30;
export const STORY_VO: VoRow[] = ''' + json.dumps(story_rows, ensure_ascii=False, indent=2) + ''';
export const DEMO_VO: VoRow[] = ''' + json.dumps(demo_rows, ensure_ascii=False, indent=2) + ''';
export const voFrames = (r: VoRow) => Math.round(r.seconds * FPS);
'''
open(os.path.join(ROOT, 'src', 'lib', 'voTiming.ts'), 'w', encoding='utf8').write(ts)
for r in story_rows:
    print('story', r['title'], r['words'], r['seconds'])
for r in demo_rows:
    print('demo ', r['title'], r['words'], r['paras'])
print('story total', round(sum(r['seconds'] for r in story_rows), 1), 'demo total', round(sum(r['seconds'] for r in demo_rows), 1))
